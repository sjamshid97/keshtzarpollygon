// نوشتن مختصات (عدد فارسی، شمارهٔ ردیف، ترتیب برعکس) و پرسش پیش از هر حذف
import { site, launch, open, suite, sleep, act, type, press, waitDialog, dialogs, closeDialogs, snap } from './h.mjs';
const st = await site(); const browser = await launch(); const S = suite('مختصات و پرسشِ پیش از حذف');
const page = await open(browser, st);
await act(page, 'proj:add'); await press(page, 'ok', 'پروژهٔ آزمایش');
await act(page, 'plot:add'); await press(page, 'ok', 'قطعهٔ آزمایش');
const id = await page.evaluate(() => state.projects[0].plots[0].id);
const ta = '[data-plot="' + id + '"] textarea[data-ring="outer"]';
const plot = () => page.evaluate(id => { const pl = state.projects[0].plots.find(x => x.id === id); return { pts: pl.points.map(p => [+p[0].toFixed(6), +p[1].toFixed(6)]), bad: pl.warnings, ha: +(netAreaM2(pl) / 10000).toFixed(4), mode: pl.mode, holes: (pl.holes || []).length, raw: pl.raw }; }, id);
const warnText = () => page.$eval('[data-plot="' + id + '"] .warn-slot', e => e.textContent);
const write = async text => { await type(page, ta, text); await sleep(450); };
const want = [[35.151538, 51.528883], [35.150378, 51.527815], [35.149341, 51.528945], [35.150312, 51.530513], [35.150966, 51.529724]];
const latin = want.map(p => p[0] + ', ' + p[1]).join('\n');
const fa = s => s.replace(/\d/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);

S.sec('نوشتن مختصات');
await write(latin); let p = await plot(); const haOk = p.ha;
S.ok(JSON.stringify(p.pts) === JSON.stringify(want) && !p.bad.length && Math.abs(haOk - 3.051) < 0.01, 'شکل معمولی (عرض, طول) مثل قبل خوانده می‌شود: ' + haOk + ' هکتار', p);
S.ok((await warnText()).trim() === '', 'هشداری نشان داده نمی‌شود', await warnText());
await write(fa(latin).replace(/\./g, '٫').replace(/,/g, '،')); p = await plot();
S.ok(JSON.stringify(p.pts) === JSON.stringify(want) && !p.bad.length, 'عددهای فارسی با ممیز و ویرگول فارسی خوانده می‌شود', p);
await write(fa(want.map(q => String(q[0]).replace('.', '/') + ' ' + String(q[1]).replace('.', '/')).join('\n'))); p = await plot();
S.ok(JSON.stringify(p.pts) === JSON.stringify(want) && !p.bad.length, 'ممیز با خط کج (۳۵/۱۵) هم خوانده می‌شود', p);
await write(want.map((q, i) => (i + 1) + '\t' + q[0] + '\t' + q[1]).join('\n')); p = await plot();
S.ok(JSON.stringify(p.pts) === JSON.stringify(want) && !p.bad.length, 'شمارهٔ ردیفِ اولِ هر خط نادیده گرفته می‌شود', p);
S.ok(/شمارهٔ ردیف/.test(await warnText()), 'و برنامه می‌گوید که چنین کرده است', await warnText());
await write(want.map((q, i) => (i + 1) + ') ' + q[0] + ', ' + q[1] + ', 1200').join('\n')); p = await plot();
S.ok(JSON.stringify(p.pts) === JSON.stringify(want), 'شمارهٔ ردیف + ارتفاع در ستون آخر هم درست خوانده می‌شود', p);
await write(want.map(q => q[0] + ', ' + q[1] + ', 1200').join('\n')); p = await plot();
S.ok(JSON.stringify(p.pts) === JSON.stringify(want) && !/شمارهٔ ردیف/.test(await warnText()), 'عرض، طول، ارتفاع (بدون شمارهٔ ردیف) مثل قبل', p);
await write(latin + '\nاین خط عدد ندارد'); p = await plot();
S.ok(p.pts.length === 5 && JSON.stringify(p.bad) === '[6]' && /خط\(های\) نامعتبر/.test(await warnText()), 'خط نامعتبر مثل قبل اعلام می‌شود', p);
await write('35°09\'05.5"N 51°31\'44.0"E\n35°09\'01.4"N 51°31\'40.1"E\n35°08\'57.6"N 51°31\'44.2"E'); p = await plot();
S.ok(p.pts.length === 3 && Math.abs(p.pts[0][0] - 35.151528) < 1e-5 && Math.abs(p.pts[0][1] - 51.528889) < 1e-5, 'درجه/دقیقه/ثانیه مثل قبل خوانده می‌شود', p.pts);

S.sec('ترتیب برعکس (اول طول، بعد عرض)');
await write(want.map(q => q[1] + ', ' + q[0]).join('\n')); p = await plot();
S.ok(p.pts[0][0] === 51.528883 && Math.abs(p.ha - 2.321) < 0.01, 'نقطه‌ها همان‌طور که نوشته شده خوانده می‌شوند (مساحت غلط: ' + p.ha + ')', p);
S.ok(/اول «طول» و بعد «عرض»/.test(await warnText()), 'ولی هشدار روشن می‌دهد', await warnText());
await act(page, 'plot:swapLL', '[data-id="' + id + '"]'); await sleep(300); p = await plot();
S.ok(JSON.stringify(p.pts) === JSON.stringify(want) && p.ha === haOk && (await warnText()).trim() === '', 'دکمهٔ «جابه‌جا کن» درستش می‌کند: ' + p.ha + ' هکتار', p);
S.ok((await page.$eval(ta, e => e.value)).startsWith('35.151538, 51.528883'), 'کادر متن هم درست می‌شود');
const undoBtn = await page.evaluate(id => [...document.querySelectorAll('[data-act="vert:undo"][data-id="' + id + '"], [data-act="plot:undo"][data-id="' + id + '"]')].map(b => b.dataset.act + (b.disabled ? ':خاموش' : ':روشن')), id);
S.ok(undoBtn.some(x => /روشن/.test(x)), 'دکمهٔ بازگردانی بعد از جابه‌جایی روشن است', undoBtn);
await page.evaluate(id => { const b = [...document.querySelectorAll('[data-act="vert:undo"][data-id="' + id + '"], [data-act="plot:undo"][data-id="' + id + '"]')].find(b => !b.disabled); if (b) b.click(); }, id); await sleep(300); p = await plot();
S.ok(p.pts[0][0] === 51.528883, 'دکمهٔ بازگردانی آن را برمی‌گرداند'); await act(page, 'plot:swapLL', '[data-id="' + id + '"]'); await sleep(300);

S.sec('تغییر «جغرافیایی / UTM»');
const sel = '[data-plot="' + id + '"] select[data-change="plot:mode"]';
await page.select(sel, 'utm'); let d = await waitDialog(page);
S.ok(d && d.title === 'تغییر نوع مختصات' && /۵ رأس/.test(d.msg), 'وقتی قطعه نقطه دارد، اول می‌پرسد', d);
await press(page, 'cancel'); await sleep(250); p = await plot();
S.ok(p.pts.length === 5 && p.mode !== 'utm' && await page.$eval(sel, e => e.value) === 'geo', '«انصراف»: نقطه‌ها می‌مانند و انتخاب به «جغرافیایی» برمی‌گردد', p);
await page.select(sel, 'utm'); await press(page, 'ok'); await sleep(250); p = await plot();
S.ok(p.pts.length === 0 && p.mode === 'utm', 'با تأیید، نوع عوض و نقطه‌ها پاک می‌شود');
await page.select(sel, 'geo'); await sleep(250); S.ok(!(await dialogs(page)).length && (await plot()).mode === 'geo', 'وقتی قطعه نقطه ندارد، بی‌پرسش عوض می‌شود');
await page.select(sel, 'utm'); await sleep(250);
const utm = await page.evaluate(w => w.map(q => { const u = latLonToUtm(q[0], q[1]); return [u.E.toFixed(1), u.N.toFixed(1), u.zone]; }), want);
await page.evaluate(([id, z]) => setPlotZone(id, z), [id, utm[0][2]]); await sleep(450);
await write(utm.map(u => u[0] + ', ' + u[1]).join('\n')); p = await plot(); const haUtm = p.ha;
S.ok(p.pts.length === 5 && Math.abs(p.pts[0][0] - want[0][0]) < 2e-6 && Math.abs(haUtm - haOk) < 0.001, 'UTM (شرقی, شمالی) مثل قبل: ' + haUtm + ' هکتار', p.pts[0]);
await write(utm.map(u => u[1] + ', ' + u[0]).join('\n')); p = await plot();
S.ok(p.pts.length === 5 && Math.abs(p.pts[0][0] - want[0][0]) < 2e-6 && p.ha === haUtm, 'UTM برعکس (شمالی, شرقی) خودکار درست خوانده می‌شود', p.pts[0]);

S.sec('پرسش پیش از حذف در برگهٔ بازدید');
await page.$eval('[data-plot="' + id + '"] [data-act="visit:add"]', e => e.click()); await sleep(400);
const vid = await page.evaluate(() => V_OPEN);
const visit = () => page.evaluate(([id, vid]) => { const v = vFind(id, vid); return { pests: (v.pests || []).length, photos: (v.photos || []).length, sig: v.sig }; }, [id, vid]);
let v = await visit(); const n0 = v.pests;
await act(page, 'visit:delRow', '[data-list="p"][data-i="0"]'); await sleep(250);
S.ok(!(await dialogs(page)).length && (await visit()).pests === n0 - 1, 'ردیفِ خالی بی‌پرسش حذف می‌شود');
await act(page, 'visit:addRow', '[data-list="p"]'); await sleep(200);
await type(page, '.vs-editor [data-input="visit:field"][data-k="p:0:name"]', 'شته'); await sleep(150);
await act(page, 'visit:delRow', '[data-list="p"][data-i="0"]'); d = await waitDialog(page);
S.ok(d && d.title === 'حذف ردیف', 'ردیفِ نوشته‌شده: اول می‌پرسد', d); await press(page, 'cancel'); await sleep(200);
S.ok((await visit()).pests === 1, '«انصراف»: ردیف می‌ماند');
await act(page, 'visit:delRow', '[data-list="p"][data-i="0"]'); await press(page, 'ok'); await sleep(250);
S.ok((await visit()).pests === 0, 'با تأیید حذف می‌شود');
// عکس
await act(page, 'visit:photo', '[data-src="gal"]'); await sleep(200);
await page.evaluate(async () => { const cv = document.createElement('canvas'); cv.width = 640; cv.height = 480; const c = cv.getContext('2d'); c.fillStyle = '#2f8f58'; c.fillRect(0, 0, 640, 480); c.fillStyle = '#fff'; c.fillRect(100, 100, 200, 120);
  const blob = await new Promise(r => cv.toBlob(r, 'image/jpeg', .85)); const el = document.getElementById('visitFile'); const dt = new DataTransfer(); dt.items.add(new File([blob], 'عکس.jpg', { type: 'image/jpeg' })); el.files = dt.files; el.dispatchEvent(new Event('change', { bubbles: true })); });
await sleep(1200); S.ok((await visit()).photos === 1, 'یک عکس اضافه شد');
await act(page, 'visit:photoDel'); d = await waitDialog(page);
S.ok(d && d.title === 'حذف عکس', 'حذف عکس: اول می‌پرسد', d); await press(page, 'cancel'); await sleep(200);
S.ok((await visit()).photos === 1, '«انصراف»: عکس می‌ماند');
await act(page, 'visit:photoDel'); await press(page, 'ok'); await sleep(400);
S.ok((await visit()).photos === 0, 'با تأیید حذف می‌شود');
// امضا
await act(page, 'visit:signClear'); await sleep(250); S.ok(!(await dialogs(page)).length, 'وقتی امضایی ثبت نشده، «پاک کردن امضا» بی‌پرسش فقط کادر را پاک می‌کند');
await page.evaluate(vid => { const cv = document.querySelector('canvas[data-sigcv="' + vid + '"]'); const c = cv.getContext('2d'); c.beginPath(); c.moveTo(10, 10); c.lineTo(120, 60); c.stroke(); cv.dataset.dirty = '1'; }, vid);
await act(page, 'visit:sign'); await press(page, 'ok', 'کشاورز آزمایشی'); await sleep(500);
S.ok(((await visit()).sig || {}).name === 'کشاورز آزمایشی', 'امضا ثبت شد');
await act(page, 'visit:signClear'); d = await waitDialog(page);
S.ok(d && d.title === 'پاک‌کردن امضا', 'پاک‌کردن امضای ثبت‌شده: اول می‌پرسد', d); await press(page, 'cancel'); await sleep(200);
S.ok(!!(await visit()).sig, '«انصراف»: امضا می‌ماند');
await act(page, 'visit:signRefuse'); d = await waitDialog(page);
S.ok(d && /آن امضا پاک می‌شود/.test(d.msg), '«امتناع از امضا» روی بازدیدِ امضاشده: اول می‌پرسد', d); await press(page, 'cancel'); await sleep(200);
S.ok(((await visit()).sig || {}).name === 'کشاورز آزمایشی', '«انصراف»: امضا می‌ماند');
await act(page, 'visit:signClear'); await press(page, 'ok'); await sleep(300);
S.ok(!(await visit()).sig, 'با تأیید پاک می‌شود');
await act(page, 'visit:signRefuse'); await press(page, 'ok', 'شاهد'); await sleep(300);
S.ok(((await visit()).sig || {}).refused === true, 'امتناع ثبت شد');
await act(page, 'visit:signRefuse'); d = await waitDialog(page);
S.ok(d && /امتناع از امضا» پاک شود/.test(d.msg), 'برداشتنِ «امتناع»: اول می‌پرسد', d); await press(page, 'cancel'); await sleep(200);
S.ok(((await visit()).sig || {}).refused === true, '«انصراف»: امتناع می‌ماند');

S.ok(page.__errors.length === 0, 'خطایی در صفحه نیست', page.__errors);
S.done(); await browser.close(); st.close();
